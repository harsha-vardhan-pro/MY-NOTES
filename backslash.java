public class backslash {
    public static void main (String[] args) {
        System.out.println("Hello \nRaja");
        System.out.println("Hello \\Raja\\");
        System.out.println("Hello \"Raja\"");
        System.out.println("Hello \t Raja");
        System.out.println("Hello \bRaja");
        System.out.println("Hello Raja");
        System.out.println("Hello\bRaja");
    }
    
}
